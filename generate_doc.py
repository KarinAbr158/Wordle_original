# ── Helpers ──────────────────────────────────────────────────────────────────
FONT = 'David'

def set_rtl(paragraph):
    pPr = paragraph._element.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.insert(0, bidi)
    jc = OxmlElement('w:jc')
    jc.set(qn('w:val'), 'right')
    pPr.append(jc)

def rtl_run(run):
    rPr = run._element.get_or_add_rPr()
    rtl = OxmlElement('w:rtl')
    rPr.append(rtl)
    cs = OxmlElement('w:cs')
    cs.set(qn('w:val'), FONT)
    rPr.append(cs)
    run.font.name = FONT

def para(text='', bold=False, size=12, center=False, heading_level=None):
    if heading_level:
        p = doc.add_heading('', level=heading_level)
    else:
        p = doc.add_paragraph()
    set_rtl(p)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    rtl_run(run)
    return p

def h1(text): return para(text, bold=True, size=16, heading_level=1)
def h2(text): return para(text, bold=True, size=14, heading_level=2)
def h3(text): return para(text, bold=True, size=12, heading_level=3)
def p(text='', bold=False, size=12): return para(text, bold=bold, size=size)
def page_break(): doc.add_page_break()

def placeholder(text):
    par = doc.add_paragraph()
    set_rtl(par)
    run = par.add_run(f'[ {text} ]')
    run.font.name = FONT
    run.font.size = Pt(12)
    run.font.color.rgb = RGBColor(0xFF, 0x00, 0x00)
    run.bold = True
    rtl_run(run)

def add_table(headers, rows):
    table = doc.add_table(rows=1+len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.RIGHT
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = h
        hdr_cells[i].paragraphs[0].runs[0].bold = True
        hdr_cells[i].paragraphs[0].runs[0].font.name = FONT
        set_rtl(hdr_cells[i].paragraphs[0])
    for row_data in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row_data):
            cells[i].text = val
            cells[i].paragraphs[0].runs[0].font.name = FONT
            set_rtl(cells[i].paragraphs[0])
    doc.add_paragraph()

# ── Header / Footer ───────────────────────────────────────────────────────────
def add_header_footer():
    sec = doc.sections[0]
    header = sec.header
    hpar = header.paragraphs[0]
    set_rtl(hpar)
    run = hpar.add_run('Wordle – אפליקציית משחק מילים יומי  |  ')
    run.font.name = FONT; run.font.size = Pt(10); rtl_run(run)
    placeholder_run = hpar.add_run('[שם התלמיד]')
    placeholder_run.font.name = FONT; placeholder_run.font.size = Pt(10)
    placeholder_run.font.color.rgb = RGBColor(0xFF,0,0)

    footer = sec.footer
    fpar = footer.paragraphs[0]
    fpar.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run2 = fpar.add_run()
    run2.font.name = FONT; run2.font.size = Pt(10)
    fld = OxmlElement('w:fldChar'); fld.set(qn('w:fldCharType'), 'begin')
    run2._r.append(fld)
    ins = OxmlElement('w:instrText'); ins.text = 'PAGE'
    run2._r.append(ins)
    fld2 = OxmlElement('w:fldChar'); fld2.set(qn('w:fldCharType'), 'end')
    run2._r.append(fld2)

add_header_footer()

